const { readFileSync } = require('node:fs');
const { runInNewContext } = require('node:vm');
const assert = require('node:assert/strict');
const source = readFileSync(require('node:path').join(__dirname, '../ruckus-unleashed-compact-ui.user.js'), 'utf8');
const start = source.indexOf('  function apRemarks(');
const end = source.indexOf('  function parseAp(', start);
const remarks = runInNewContext(source.slice(start, end) + '\napRemarks');
const normal = {state: 1, raw: {}, upSpeed: 1000, upDuplex: 'full', upErr: 0, busy24: 0, busy5: null};
assert.equal(remarks(normal), '');
assert.equal(remarks({...normal, raw: {'poe-mode': '9'}}), '');
const power = {...normal, raw: {'poe-mode-warning-code': 'UN_LIMIT_FUNCTION_POE_MODE_WARNING'}};
assert.equal(remarks(power), 'Insufficient power: functions limited');
assert.equal(remarks({...power, state: 0, busy5: 80}), 'Offline');
assert.equal(remarks({...normal, busy5: 30}), '');
assert.match(remarks({...normal, busy5: 30.1}), /5 GHz non-Wi-Fi busy: 30.1%/);
const combined = remarks({...power, upSpeed: 100, upDuplex: 'half', upErr: 2});
assert.match(combined, /Insufficient power/);
assert.match(combined, /Uplink 100 Mbps/);
assert.match(combined, /half duplex/);
assert.match(combined, /errors: 2 \(counter\)/);
assert.match(remarks({...normal, raw: {'poe-mode-warning-code': 'NEW_CODE'}}), /Power warning: NEW_CODE/);
console.log('AP remarks checks passed.');

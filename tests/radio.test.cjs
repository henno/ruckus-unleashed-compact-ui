const { readFileSync } = require('node:fs');
const { runInNewContext } = require('node:vm');
const assert = require('node:assert/strict');
const source = readFileSync(require('node:path').join(__dirname, '../ruckus-unleashed-compact-ui.user.js'), 'utf8');
const start = source.indexOf('  function parseRadio(');
const end = source.indexOf('  function parseAp(', start);
const { parseRadio, rfValue } = runInNewContext(source.slice(start, end) + '\n({parseRadio, rfValue})');
const sample = { 'radio-band': '5g', 'rf-samples': '10', 'airtime-total': '229', 'airtime-busy': '4', 'airtime-rx': '205', 'airtime-tx': '21', noisefloor: '-106', phyerr: '20' };
const r = parseRadio(sample, true);
assert.equal(r.total, 22.9);
assert.equal(r.busy, 0.4);
assert.equal(r.noise, -106);
assert.equal(r.phy, 2);
assert.equal(parseRadio(sample, false).busy, null);
assert.equal(parseRadio({...sample, 'rf-samples': '0'}, true).total, null);
assert.equal(parseRadio({...sample, 'airtime-busy': ''}, true).busy, null);
assert.equal(parseRadio({...sample, 'airtime-busy': 'bad'}, true).busy, null);
assert.equal(parseRadio({...sample, 'airtime-busy': '-1'}, true).busy, null);
assert.equal(parseRadio({...sample, 'airtime-busy': '1001'}, true).busy, null);
assert.equal(parseRadio({...sample, 'airtime-busy': '0'}, true).busy, 0);
assert.equal(parseRadio({}, true).noise, null);
assert.equal(rfValue(null), '—');
assert.equal(rfValue(0, 1, '%'), '0.0%');
console.log('Radio calculation checks passed.');
const traffic = {...sample, 'radio-total-tx-mcast':'10', 'radio-total-tx-fail':'2', 'radio-total-tx-pkts':'88', 'radio-total-retries':'5'};
assert.equal(parseRadio(traffic, true).retries, 5);
assert.equal(parseRadio(traffic, true).drops, 2);
assert.equal(parseRadio(traffic, false).retries, null);
assert.equal(parseRadio({...traffic, 'radio-total-tx-pkts':''}, true).retries, null);
assert.equal(parseRadio(sample, true).drops, null);
console.log('Retry/drop calculation checks passed.');
